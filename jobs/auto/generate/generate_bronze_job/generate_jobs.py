"""
Approach A — generate one standalone bronze job file per active job of auto/bronze_tables.csv
(columns from auto/bronze_columns.csv), written straight to its
final place with the naming rule <layer>__<table>.py:

    templates/snapshot_job.py.tpl     → jobs/bronze/<domain>/bronze__<target_table>.py   (load_type = snapshot)
    templates/incremental_job.py.tpl  → jobs/bronze/<domain>/bronze__<target_table>.py   (load_type = incremental)

Generated files start with the marker line "AUTO-GENERATED by jobs/auto/generate/generate_bronze_job/generate_jobs.py".
Every run:
    1. validates the configuration incl. Postgres checks (validate/validate_config.py; --offline = file checks only);
       exact duplicate column rows are removed from bronze_columns.csv; nothing is generated if there is an error,
    2. deletes the generated files of the previous run that are no longer in the CSV (or now active=0) — only files
       that carry the marker; hand-written files and other code in jobs/bronze/ are never deleted,
    3. writes one file per active CSV row. A hand-written file with the same name is REPLACED (reported in the output).
Never edit a generated file by hand: change the CSV or a template and regenerate.
The generated jobs only share jobs/bronze/bronze_columns.py and jobs/common/parsers.py, like the hand-written jobs.

Plain Python, no Spark. Run (from the host, inside the container so paths and Python 3.8 match the jobs):
    docker exec spark-client-dungafk python3 /home/spark/jobs/auto/generate/generate_bronze_job/generate_jobs.py
"""
import argparse
import glob
import os
import sys
from string import Template

GENERATE_DIR = os.path.dirname(os.path.abspath(__file__))                 # jobs/auto/generate/generate_bronze_job
AUTO_DIR = os.path.dirname(os.path.dirname(GENERATE_DIR))                 # jobs/auto
JOBS_DIR = os.path.dirname(AUTO_DIR)                                      # jobs
sys.path.insert(0, AUTO_DIR)                                              # → job_config.py
from job_config import DEFAULT_COLUMNS, DEFAULT_TABLES, INCREMENTAL, JobConfig, load_jobs, type_code  # noqa: E402

LAYER = "bronze"
TARGET_DIR = os.path.join(JOBS_DIR, LAYER)                                # jobs/bronze → <domain>/bronze__<table>.py
TEMPLATE_DIR = os.path.join(GENERATE_DIR, "templates")
TEMPLATES = {"snapshot": "snapshot_job.py.tpl", INCREMENTAL: "incremental_job.py.tpl"}
MARKER = "AUTO-GENERATED by jobs/auto/generate/generate_bronze_job/generate_jobs.py"


def schema_code(job: JobConfig) -> str:
    """Python code of the job's StructType SCHEMA (one StructField per CSV column), or None for all columns."""
    if not job.columns:
        return "None"
    fields = "".join(f'    StructField("{name}", {type_code(type_name)}),\n' for name, type_name in job.columns)
    return "StructType([\n" + fields + "])"


def job_path(job: JobConfig) -> str:
    return os.path.join(TARGET_DIR, job.domain, f"{LAYER}__{job.target_table}.py")


def is_generated(path: str) -> bool:
    """True if the file was written by this generator (marker in its header)."""
    with open(path, encoding="utf-8") as f:
        return MARKER in f.read(500)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate one bronze job file per active job of the CSV")
    parser.add_argument("--tables-config", default=DEFAULT_TABLES, help="table list CSV (default: auto/bronze_tables.csv)")
    parser.add_argument("--columns-config", default=DEFAULT_COLUMNS,
                        help="column list CSV (default: auto/bronze_columns.csv)")
    parser.add_argument("--offline", action="store_true", help="skip the Postgres checks of the configuration")
    args = parser.parse_args()

    try:
        jobs = [j for j in load_jobs(args.tables_config, args.columns_config, check_source=not args.offline,
                                  fix_duplicates=True) if j.active]   # validate before touching anything
    except ValueError as exc:
        print(f"✘ {exc}")
        return 2
    templates = {}
    for load_type, name in TEMPLATES.items():
        with open(os.path.join(TEMPLATE_DIR, name), encoding="utf-8") as f:
            templates[load_type] = Template(f.read())
    wanted = {os.path.abspath(job_path(j)) for j in jobs}

    # 1. Remove generated files of earlier runs that are no longer wanted (marker files only)
    for path in sorted(glob.glob(os.path.join(TARGET_DIR, "*", f"{LAYER}__*.py"))):
        if os.path.abspath(path) not in wanted and is_generated(path):
            os.remove(path)
            print(f"✔ removed stale generated job {os.path.relpath(path, JOBS_DIR)}")
            domain_dir = os.path.dirname(path)
            if not os.listdir(domain_dir):
                os.rmdir(domain_dir)

    # 2. Write one file per active job
    for job in jobs:
        # *_LIT values are Python literals (repr) so quotes in filters / column lists stay valid code
        code = templates[job.load_type].substitute(
            SOURCE_TABLE=job.source_table, DOMAIN=job.domain, TARGET_TABLE=job.target_table,
            EVENT_COL=job.event_col or "",
            SOURCE_TABLE_LIT=repr(job.source_table), DOMAIN_LIT=repr(job.domain),
            TARGET_TABLE_LIT=repr(job.target_table), EVENT_COL_LIT=repr(job.event_col),
            SCHEMA_CODE=schema_code(job),
            SOURCE_FILTER_LIT=repr(job.source_filter))
        assert MARKER in code[:500], "template must start with the generator marker"
        path = job_path(job)
        note = ""
        if os.path.exists(path):
            note = "  (updated)" if is_generated(path) else "  (REPLACED a hand-written file)"
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:   # LF: files run in Linux containers
            f.write(code)
        print(f"✔ {job.load_type:<12} {os.path.relpath(path, JOBS_DIR)}{note}")

    print(f"\n{len(jobs)} job file(s) generated under {TARGET_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
